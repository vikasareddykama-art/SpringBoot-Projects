package com.example.busbooking.service;

import com.example.busbooking.dto.BusBookingDTO;
import com.example.busbooking.entity.BusBooking;
import com.example.busbooking.exception.DuplicateSeatException;
import com.example.busbooking.exception.InvalidBookingException;
import com.example.busbooking.exception.ResourceNotFoundException;
import com.example.busbooking.repository.BusRepository;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.util.Comparator;
import java.util.List;
import java.util.Locale;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

/**
 * Layer 2 - business logic. Every write goes through validate(), which enforces:
 *  1. passenger name and bus number not empty
 *  2. source and destination different
 *  3. seat number between 1 and 50
 *  4. travel date today or later
 *  5. ticket fare greater than zero
 *  6. no duplicate seat for the same bus number and travel date
 */
@Service
@Transactional
public class BusBookingServiceImpl implements BusBookingService {

    private static final int MIN_SEAT = 1;
    private static final int MAX_SEAT = 50;

    private final BusRepository busRepository;

    public BusBookingServiceImpl(BusRepository busRepository) {
        this.busRepository = busRepository;
    }

    // ------------------------------------------------------------------ CRUD

    @Override
    public BusBookingDTO addBooking(BusBookingDTO dto) {
        validate(dto, null);
        BusBooking booking = new BusBooking();
        copyToEntity(dto, booking); // BookingID is generated by the database
        return toDto(busRepository.saveAndFlush(booking));
    }

    @Override
    @Transactional(readOnly = true)
    public List<BusBookingDTO> getAllBookings() {
        return toDtoList(busRepository.findAll());
    }

    @Override
    @Transactional(readOnly = true)
    public BusBookingDTO getBookingById(Integer id) {
        return toDto(findOrThrow(id));
    }

    @Override
    public BusBookingDTO updateBooking(Integer id, BusBookingDTO dto) {
        BusBooking existing = findOrThrow(id);
        validate(dto, id);
        copyToEntity(dto, existing);
        return toDto(busRepository.saveAndFlush(existing));
    }

    @Override
    public void cancelBooking(Integer id) {
        BusBooking existing = findOrThrow(id);
        busRepository.delete(existing);
    }

    // --------------------------------------------------------------- Reports

    @Override
    @Transactional(readOnly = true)
    public List<BusBookingDTO> getRouteReport(String source, String dest) {
        if (isBlank(source) || isBlank(dest)) {
            throw new InvalidBookingException("Both source and destination are required for the route report");
        }
        return toDtoList(busRepository
                .findBySourceIgnoreCaseAndDestinationIgnoreCase(source.trim(), dest.trim()));
    }

    @Override
    @Transactional(readOnly = true)
    public List<BusBookingDTO> getDateReport(LocalDate travelDate) {
        if (travelDate == null) {
            throw new InvalidBookingException("Travel date is required for the date report");
        }
        return toDtoList(busRepository.findByTravelDate(travelDate));
    }

    @Override
    @Transactional(readOnly = true)
    public List<BusBookingDTO> getPassengerReport(String passengerName) {
        if (isBlank(passengerName)) {
            throw new InvalidBookingException("Passenger name is required for the passenger report");
        }
        return toDtoList(busRepository.findByPassengerNameIgnoreCase(passengerName.trim()));
    }

    // ------------------------------------------------------------ Validation

    private void validate(BusBookingDTO dto, Integer excludeBookingId) {
        if (dto == null) {
            throw new InvalidBookingException("Booking details are required");
        }
        if (isBlank(dto.getPassengerName())) {
            throw new InvalidBookingException("Passenger name must not be empty");
        }
        if (isBlank(dto.getBusNumber())) {
            throw new InvalidBookingException("Bus number must not be empty");
        }
        if (isBlank(dto.getSource())) {
            throw new InvalidBookingException("Source must not be empty");
        }
        if (isBlank(dto.getDestination())) {
            throw new InvalidBookingException("Destination must not be empty");
        }
        if (dto.getSource().trim().equalsIgnoreCase(dto.getDestination().trim())) {
            throw new InvalidBookingException("Source and destination must be different");
        }
        Integer seat = dto.getSeatNumber();
        if (seat == null || seat < MIN_SEAT || seat > MAX_SEAT) {
            throw new InvalidBookingException(
                    "Seat number must be between " + MIN_SEAT + " and " + MAX_SEAT);
        }
        if (dto.getTravelDate() == null) {
            throw new InvalidBookingException("Travel date is required");
        }
        if (dto.getTravelDate().isBefore(LocalDate.now())) {
            throw new InvalidBookingException("Travel date must be today or a future date");
        }
        if (dto.getTicketFare() == null || dto.getTicketFare().compareTo(BigDecimal.ZERO) <= 0) {
            throw new InvalidBookingException("Ticket fare must be greater than zero");
        }

        // Same bus + same date + same seat is not allowed; other buses may reuse the seat number.
        String busNumber = normalizeBusNumber(dto.getBusNumber());
        boolean seatTaken = (excludeBookingId == null)
                ? busRepository.existsByBusNumberIgnoreCaseAndTravelDateAndSeatNumber(
                        busNumber, dto.getTravelDate(), seat)
                : busRepository.existsByBusNumberIgnoreCaseAndTravelDateAndSeatNumberAndBookingIdNot(
                        busNumber, dto.getTravelDate(), seat, excludeBookingId);
        if (seatTaken) {
            throw new DuplicateSeatException("Seat " + seat + " on bus " + busNumber
                    + " is already booked for " + dto.getTravelDate() + ". Choose a different seat.");
        }
    }

    // --------------------------------------------------------------- Helpers

    private BusBooking findOrThrow(Integer id) {
        return busRepository.findById(id)
                .orElseThrow(() -> new ResourceNotFoundException("Booking with ID " + id + " was not found"));
    }

    private void copyToEntity(BusBookingDTO dto, BusBooking booking) {
        booking.setPassengerName(dto.getPassengerName().trim());
        booking.setBusNumber(normalizeBusNumber(dto.getBusNumber()));
        booking.setSource(dto.getSource().trim());
        booking.setDestination(dto.getDestination().trim());
        booking.setTravelDate(dto.getTravelDate());
        booking.setSeatNumber(dto.getSeatNumber());
        booking.setTicketFare(dto.getTicketFare());
    }

    private BusBookingDTO toDto(BusBooking b) {
        return new BusBookingDTO(b.getBookingId(), b.getPassengerName(), b.getBusNumber(), b.getSource(),
                b.getDestination(), b.getTravelDate(), b.getSeatNumber(), b.getTicketFare());
    }

    private List<BusBookingDTO> toDtoList(List<BusBooking> bookings) {
        return bookings.stream()
                .sorted(Comparator.comparing(BusBooking::getBookingId))
                .map(this::toDto)
                .toList();
    }

    private String normalizeBusNumber(String busNumber) {
        return busNumber.trim().toUpperCase(Locale.ROOT);
    }

    private boolean isBlank(String value) {
        return value == null || value.trim().isEmpty();
    }
}
